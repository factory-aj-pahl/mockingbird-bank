-- Account programs: customer date of birth, account currency, and program
-- participation. Existing rows keep working unchanged: date_of_birth starts
-- empty, every existing account is recorded as USD (the only currency the app
-- has ever held), and no account is enrolled in a program.

ALTER TABLE account_holder ADD COLUMN date_of_birth DATE;

ALTER TABLE account
    ADD COLUMN currency VARCHAR(3) NOT NULL DEFAULT 'USD'
        CONSTRAINT account_currency_iso_code CHECK (currency ~ '^[A-Z]{3}$');

CREATE TABLE program_participation (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    holder_id    BIGINT NOT NULL REFERENCES account_holder (id),
    program_type VARCHAR(255) NOT NULL
        CONSTRAINT program_participation_known_type
            CHECK (program_type IN ('REGULAR', 'YOUTH_SAVINGS')),
    -- Target of account_program_participation_same_holder below.
    CONSTRAINT program_participation_id_holder_key UNIQUE (id, holder_id)
);

CREATE INDEX program_participation_holder_idx ON program_participation (holder_id);

-- An account takes part in at most one program, so the link is a single column
-- on the account row. The foreign key includes holder_id, so the database
-- rejects linking an account to a participation that belongs to a different
-- customer. A NULL link (no program) is not checked.
ALTER TABLE account ADD COLUMN program_participation_id BIGINT;

ALTER TABLE account
    ADD CONSTRAINT account_program_participation_same_holder
        FOREIGN KEY (program_participation_id, holder_id)
        REFERENCES program_participation (id, holder_id);

CREATE INDEX account_program_participation_idx ON account (program_participation_id);
