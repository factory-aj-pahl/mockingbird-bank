#!/usr/bin/env bash
# Build the current working tree into an image and (re)deploy it, plus an
# in-cluster Postgres, to the local k3d cluster - the inner loop for seeing a
# change running in Kubernetes before it goes anywhere near master.
#
#   ./scripts/k3d-deploy.sh               build, import, apply, wait for rollout
#   ./scripts/k3d-deploy.sh status        pods/services/ingress/PVC in the namespace
#   ./scripts/k3d-deploy.sh logs [postgres]  follow app (or Postgres) logs
#   ./scripts/k3d-deploy.sh down          remove the app, stop Postgres, KEEP its data
#   ./scripts/k3d-deploy.sh down --purge-db   delete the whole namespace, data included
#
# Override the target with CONTEXT=... CLUSTER=... (defaults: k3d-dev-k8s /
# dev-k8s). Every kubectl call is pinned to that context, never the current one.
#
# Each build gets a unique tag (dev-<sha>[-dirty]-<timestamp>) so the
# Deployment spec actually changes and Kubernetes rolls a new pod; re-using a
# fixed tag with IfNotPresent would keep running the previously cached image.
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT_DIR"

CONTEXT="${CONTEXT:-k3d-dev-k8s}"
CLUSTER="${CLUSTER:-dev-k8s}"
NAMESPACE="mockingbird-bank-dev"
IMAGE_REPO="mockingbird-bank"
APP_HOST="mockingbird.localhost"
ROLLOUT_TIMEOUT="${ROLLOUT_TIMEOUT:-300s}"
# Kustomize refuses absolute paths to a base, so the per-build overlay lives
# inside the repo (build/ is gitignored and excluded from the Docker context).
OVERLAY_DIR="$ROOT_DIR/build/k3d-deploy"

kc() { kubectl --context "$CONTEXT" "$@"; }

preflight() {
    local cmd
    for cmd in docker k3d kubectl git; do
        command -v "$cmd" >/dev/null 2>&1 || { echo "Missing required command: $cmd" >&2; exit 1; }
    done
    docker info >/dev/null 2>&1 || { echo "Docker daemon is not running." >&2; exit 1; }
    if ! kubectl config get-contexts -o name | grep -qx "$CONTEXT"; then
        echo "kube context '$CONTEXT' not found (set CONTEXT=...)." >&2
        exit 1
    fi
    k3d cluster get "$CLUSTER" >/dev/null 2>&1 || { echo "k3d cluster '$CLUSTER' not found (set CLUSTER=...)." >&2; exit 1; }
}

# Host port the k3d loadbalancer maps to the cluster's port 80 (Traefik).
http_port() {
    docker port "k3d-${CLUSTER}-serverlb" 80/tcp 2>/dev/null | awk -F: 'NR==1 {print $NF}'
}

app_url() {
    local port
    port="$(http_port)"
    if [[ -z "$port" ]]; then
        echo ""
    elif [[ "$port" == "80" ]]; then
        echo "http://${APP_HOST}"
    else
        echo "http://${APP_HOST}:${port}"
    fi
}

image_tag() {
    local tag
    tag="dev-$(git rev-parse --short HEAD)"
    if [[ -n "$(git status --porcelain)" ]]; then
        tag+="-dirty"
    fi
    echo "${tag}-$(date +%Y%m%d%H%M%S)"
}

show_status() {
    kc -n "$NAMESPACE" get pods,svc,ingress,pvc
}

deploy() {
    local tag image start url version metadata build_args
    start=$(date +%s)
    tag="$(image_tag)"
    image="${IMAGE_REPO}:${tag}"
    # The Docker build context has no .git, so the version and commit the app
    # reports (/actuator/info, startup log, top bar) have to come in as build args.
    metadata="$(./scripts/build-metadata.sh --docker-args)"
    read -r -a build_args <<<"$metadata"
    version="$(./scripts/build-metadata.sh | sed -n 's/^APP_VERSION=//p')"

    echo "== Mockingbird Bank: k3d deploy ($CONTEXT, image $image, version $version) =="

    echo "Building $image (native arch; first build takes a few minutes)..."
    docker build "${build_args[@]}" -t "$image" -t "${IMAGE_REPO}:dev" .

    echo "Importing image into k3d cluster '$CLUSTER'..."
    k3d image import "$image" "${IMAGE_REPO}:dev" -c "$CLUSTER"

    mkdir -p "$OVERLAY_DIR"
    cat >"$OVERLAY_DIR/kustomization.yaml" <<YAML
# Generated by scripts/k3d-deploy.sh - pins the app to this build's image tag.
apiVersion: kustomize.config.k8s.io/v1beta1
kind: Kustomization
resources:
  - ../../k8s/local
images:
  - name: ${IMAGE_REPO}
    newTag: ${tag}
YAML

    echo "Applying k8s/local (namespace $NAMESPACE)..."
    kc apply -k "$OVERLAY_DIR"

    echo "Waiting for Postgres..."
    kc -n "$NAMESPACE" rollout status statefulset/postgres --timeout="$ROLLOUT_TIMEOUT"
    echo "Waiting for the app rollout (Spring + Flyway startup takes ~20-60s)..."
    if ! kc -n "$NAMESPACE" rollout status deployment/mockingbird-app --timeout="$ROLLOUT_TIMEOUT"; then
        echo
        echo "Rollout did not finish. Current state:" >&2
        show_status >&2 || true
        echo "Inspect with: $0 logs   or   kubectl --context $CONTEXT -n $NAMESPACE describe pod -l app=mockingbird-app" >&2
        exit 1
    fi

    echo
    show_status
    echo
    url="$(app_url)"
    if [[ -n "$url" ]]; then
        echo "Deployed $image in $(($(date +%s) - start))s."
        echo "Open:   $url"
        echo "Health: curl $url/actuator/health"
        echo "Version: $version (curl $url/actuator/info)"
    else
        echo "Deployed $image, but the k3d loadbalancer has no host port mapped to 80."
        echo "Reach it with: kubectl --context $CONTEXT -n kube-system port-forward svc/traefik 8081:80"
        echo "then open http://${APP_HOST}:8081"
    fi
    echo "Login:  jordan.ellis / mockingbird (seeded on an empty database)"
}

down() {
    if [[ "${1:-}" == "--purge-db" ]]; then
        echo "Deleting namespace $NAMESPACE, INCLUDING the Postgres PVC and all its data..."
        kc delete namespace "$NAMESPACE" --ignore-not-found --wait=true
        return
    fi
    echo "Removing the app from $NAMESPACE and stopping Postgres..."
    kc -n "$NAMESPACE" delete deployment/mockingbird-app service/mockingbird-app ingress/mockingbird-app --ignore-not-found
    kc -n "$NAMESPACE" scale statefulset/postgres --replicas=0 2>/dev/null || true
    echo "Kept the Postgres PVC (data survives the next deploy):"
    kc -n "$NAMESPACE" get pvc 2>/dev/null || true
    echo "To wipe it too: $0 down --purge-db"
}

logs() {
    case "${1:-app}" in
        app) kc -n "$NAMESPACE" logs -f deployment/mockingbird-app --all-containers=false ;;
        postgres | db) kc -n "$NAMESPACE" logs -f statefulset/postgres ;;
        *) echo "Usage: $0 logs [app|postgres]" >&2; exit 1 ;;
    esac
}

preflight
case "${1:-deploy}" in
    deploy | up) deploy ;;
    status) show_status ;;
    logs) logs "${2:-app}" ;;
    down) down "${2:-}" ;;
    -h | --help | help) sed -n '2,17p' "$0" ;;
    *) echo "Unknown command: $1 (try: deploy, status, logs, down, help)" >&2; exit 1 ;;
esac
